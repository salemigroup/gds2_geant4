"""
detector_builder.py — generate the Geant4 detector construction.

Imported by make_geant4.py. Emits a construction.hh/.cc pair in the style of a
hand-written G4CMP detector construction: world, substrate, the generated
components stacked on the substrate, then lattices, surface properties and
border surfaces.

Boundaries are resolved per pair of touching volumes. A pair matches a specific
rule if one names both volumes; otherwise it falls back to the rule for that
pair of materials.
"""

from __future__ import annotations

import sys
from collections import OrderedDict

from shapely.strtree import STRtree


# --------------------------------------------------------------- adjacency
def find_touching(items, substrate_layer, tol_um):
    """Pairs of placed volumes that share a face.

    Three kinds. Everything meets the world on its exposed faces. Everything
    sitting on the substrate meets the substrate. Two volumes on the stack meet
    each other when their footprints touch, which after the gap snapping means
    a distance of zero.
    """
    subs = [it for it in items if it["layer"] == substrate_layer]
    stack = [it for it in items if it["layer"] != substrate_layer]

    pairs = []
    for it in items:
        pairs.append((it, None))                      # against the world

    for a in stack:
        for s in subs:
            if a["geom"].intersects(s["geom"]):
                pairs.append((a, s))

    if len(stack) > 1:
        geoms = [it["geom"] for it in stack]
        tree = STRtree(geoms)
        for i, a in enumerate(stack):
            for j in tree.query(a["geom"].buffer(tol_um)):
                if j <= i:
                    continue
                if geoms[i].distance(geoms[j]) <= tol_um:
                    pairs.append((a, stack[j]))
    return pairs


def resolve_boundary(a, b, cfg, world_material):
    """The boundary rule for one pair: a specific rule wins over a material one."""
    bnd = cfg.get("boundaries", {})
    name_a = a["name"]
    name_b = b["name"] if b is not None else "world"
    mat_a = a["material"]
    mat_b = b["material"] if b is not None else world_material

    for rule in bnd.get("specific", []):
        want = set(rule["volumes"])
        if want == {name_a, name_b}:
            return rule, "specific"

    for rule in bnd.get("defaults", []):
        if sorted(rule["materials"]) == sorted([mat_a, mat_b]):
            return rule, "material"
    return None, None


